def apply_correction(s_raw: float, c: float) -> float:
    """
    話者ごとの継続補正を適用し、補正後スコア x を算出する

    責務：
    ・特定の話者の s_raw に対して、その話者固有の係数 c を用いてスコアを増幅する
    ・x = s_raw * c を算出し、100でクリップする
    """

    # =========================
    # 入力値の安全処理
    # =========================
    s_raw = _clamp(s_raw, 0.0, 100.0)

    # c は structural_pressure で算出された話者固有の係数（1.0〜1.5想定）
    if c < 1.0:
        c = 1.0

    # =========================
    # 補正計算
    # =========================
    # 計算式: x = S_raw × c
    x = s_raw * c

    # =========================
    # 出力の安全処理（最大100に収める）
    # =========================
    return _clamp(x, 0.0, 100.0)


# =========================
# 内部関数
# =========================

def _clamp(value: float, min_val: float, max_val: float) -> float:
    """値を範囲内に収める"""
    return max(min_val, min(value, max_val))