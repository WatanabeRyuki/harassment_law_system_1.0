import math

def calc_final_score(x: float, a: float = 0.12, b: float = 50.0) -> float:
    """
    話者ごとの最終Sスコアを算出する（0〜100）

    責務：
    ・シグモイド関数による非線形変換を適用し、微細な差異を「圧」として強調
    ・特定の話者の補正後スコア x を、最終的な攻撃性指標 S に変換する

    Parameters:
    - x: 話者ごとの補正後スコア（S_raw × c）
    - a: 傾き（感度。デフォルト 0.08）
    - b: シグモイドの中心（境界線。デフォルト 50）
    """

    # シグモイドの入力 z を計算
    z = a * (x - b)

    # =========================
    # 指数関数のオーバーフロー対策
    # =========================
    if z > 60:
        return 100.0
    elif z < -60:
        return 0.0

    # =========================
    # シグモイド計算 (0〜100スケール)
    # =========================
    # 100 / (1 + e^-z)
    S = 100 / (1 + math.exp(-z))

    return _clamp(S, 0.0, 100.0)


# =========================
# 内部関数
# =========================

def _clamp(value: float, min_val: float, max_val: float) -> float:
    """値を範囲内に収める"""
    return max(min_val, min(value, max_val))