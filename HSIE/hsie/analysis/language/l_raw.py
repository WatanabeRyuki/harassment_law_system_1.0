# -*- coding: utf-8 -*-

"""
l_raw.py

責務：
・I, C, D から L_raw を算出
・数式適用のみ

禁止事項：
・スコア補正（ルール的処理）
・カテゴリ判定
・Evidence操作
"""

def calc_l_raw(I: float, C: float, D: float, alpha: float = 0.2) -> float:
    """
    入力：
        I, C, D（0〜100想定）

    出力：
        L_raw（0〜100）
    """

    # =========================
    # ■ 入力クリップ（安全）
    # =========================
    I = _clip(I)
    C = _clip(C)
    D = _clip(D)

    # =========================
    # ■ 基本スコア（最大圧）
    # =========================
    base = max(I, C, D)

    # =========================
    # ■ 複合補正
    # =========================
    composite = (I + C + D - base) / 2

    l_raw = base + alpha * composite

    # =========================
    # ■ 最終クリップ
    # =========================
    l_raw = _clip(l_raw)

    # =========================
    # ■ 安定化（小数丸め）
    # =========================
    return round(l_raw, 2)


# =========================
# ■ 内部ユーティリティ
# =========================
def _clip(value: float) -> float:
    """
    0〜100に制限
    """
    if value < 0:
        return 0.0
    if value > 100:
        return 100.0
    return value